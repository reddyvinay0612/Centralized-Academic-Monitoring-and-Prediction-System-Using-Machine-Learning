def parse_and_save():
    sections = RAW_DATA_TEXT.strip().split('SPLIT_SECTION')
    dept_dfs = []
    
    # Map each section to its department code
    dept_mapping = {
        'ME': 'ME',
        'IS': 'ISE',
        'EE': 'EEE',
        'EC': 'ECE',
        'CV': 'CV',
        'CG': 'CSD',  # CG stands for Computer Science & Design / Graphics
        'CE': 'CE',   # Computer Engineering
        'CD': 'CSD',  # Computer Science and Design
        'AI': 'AIML'
    }

    total_parsed = 0
    for idx, sec in enumerate(sections):
        lines = [l.strip() for l in sec.strip().split('\n') if l.strip()]
        if not lines:
            continue
        
        # Keep only lines up to "Check,Value"
        valid_lines = []
        for line in lines:
            if line.startswith('Check,') or line.startswith('"SYNTHETIC') or line.startswith('Students (rows)'):
                break
            valid_lines.append(line)
        
        csv_text = '\n'.join(valid_lines)
        df = pd.read_csv(io.StringIO(csv_text))
        
        # Clean column names
        df.columns = [
            c.strip().replace(' ', '_').replace('_(/100)', '').replace('_(proxy,_/30)', '').replace('%', 'pct').replace('-', '_')
            for c in df.columns
        ]
        
        # Deduce department code from first USN
        sample_usn = str(df['USN'].iloc[0])
        # e.g. 4PM23ME001 -> ME
        match = re.search(r'4PM\d\d([A-Z]+)\d+', sample_usn)
        branch_tag = match.group(1) if match else f'SEC_{idx}'
        dept_code = dept_mapping.get(branch_tag, branch_tag)
        
        df['department'] = dept_code
        dept_dfs.append(df)
        
        out_path = os.path.join('data', 'processed', f'dept_{dept_code}.csv')
        df.to_csv(out_path, index=False)
        print(f"[+] Saved {len(df)} records for Department {dept_code} to {out_path}")
        total_parsed += len(df)
        
    print(f"\n[*] Total new department students parsed: {total_parsed}")
    
    # Also load existing CSE dataset if available
    cse_path = os.path.join('data', 'processed', 'pesitm_sem6_students_evaluation.csv')
    if os.path.exists(cse_path):
        cse_df = pd.read_csv(cse_path)
        cse_df['department'] = 'CSE'
        dept_dfs.append(cse_df)
        print(f"[+] Appended {len(cse_df)} records for CSE from {cse_path}")
    
    # Combine all into master dataset
    master_df = pd.concat(dept_dfs, ignore_index=True)
    master_path = os.path.join('data', 'processed', 'pesitm_multi_department_master.csv')
    master_df.to_csv(master_path, index=False)
    print(f"\n[✓] Master dataset created with {len(master_df)} students across {master_df['department'].nunique()} departments: {master_df['department'].unique().tolist()}")
    print(f"    Saved to: {master_path}")

if __name__ == '__main__':
    parse_and_save()
